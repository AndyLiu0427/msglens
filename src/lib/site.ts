export const LOCALES = ["en", "zh"] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = "en";

/**
 * Map a route path (without locale prefix) to its absolute URL for a locale.
 *
 * Emits a trailing slash to match `trailingSlash: true` in next.config, so the
 * URLs in the sitemap are byte-identical to the canonical tags on the pages
 * they point at. A mismatch here reads to a crawler as two distinct URLs.
 */
export function localizedUrl(path: string, locale: Locale): string {
  const clean = path === "/" ? "" : path.replace(/^\/|\/$/g, "");
  const prefix = locale === DEFAULT_LOCALE ? "" : `/${locale}`;
  return `${SITE.url}${prefix}${clean ? `/${clean}` : ""}/`;
}

export function localizedPath(path: string, locale: Locale): string {
  const clean = path === "/" ? "" : path.replace(/^\/|\/$/g, "");
  const prefix = locale === DEFAULT_LOCALE ? "" : `/${locale}`;
  return `${prefix}${clean ? `/${clean}` : ""}` || "/";
}

