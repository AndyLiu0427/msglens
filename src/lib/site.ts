/**
 * Normalise the configured origin.
 *
 * A trailing slash in the env var is an easy thing to type and produces `//`
 * in every canonical, hreflang and sitemap URL — which crawlers read as a
 * different page than the one actually served. Strip it here rather than
 * relying on whoever sets the variable to get it right.
 */
function normaliseOrigin(value: string): string {
  return value.trim().replace(/\/+$/, "");
}

